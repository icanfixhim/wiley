function renderTranslation(translation) {
  const readerText = document.querySelector("#reader-text");
  readerText.replaceChildren();
  for (const block of (translation || "번역본 준비 중").split(/\n\s*\n/)) {
    const lines = block.split("\n");
    const sectionTitle = lines[0].match(/^\[(.+)\]$/);
    if (sectionTitle) {
      const heading = document.createElement("h3");
      heading.textContent = sectionTitle[1];
      readerText.append(heading);
      lines.shift();
    }
    if (lines.length && lines.every(line => line.startsWith("- "))) {
      const list = document.createElement("ul");
      for (const line of lines) {
        const item = document.createElement("li");
        item.textContent = line.slice(2);
        list.append(item);
      }
      readerText.append(list);
    } else if (lines.length) {
      const paragraph = document.createElement("p");
      const segments = lines.join("\n").split(/(\*\*[^*\n]+\*\*)/);
      segments.forEach((segment, index) => {
        if (index % 2 === 0) {
          paragraph.append(segment);
        } else {
          const emphasis = document.createElement("strong");
          emphasis.textContent = segment.slice(2, -2);
          paragraph.append(emphasis);
        }
      });
      readerText.append(paragraph);
    }
  }
}

