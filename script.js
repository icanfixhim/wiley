async function openCard(button) {
  trigger = button;
  const id = ++viewId;
  const character = characters[button.dataset.character];
  readerPanel.hidden = true;
  cardPanel.hidden = false;
  dialog.setAttribute("aria-labelledby", "card-name");
  cardPanel.querySelectorAll("[data-field]").forEach(node => {
    node.textContent = character[node.dataset.field];
  });
  saveLink.removeAttribute("href");
  saveLink.setAttribute("aria-disabled", "true");
  photoFrame.replaceChildren();
  photoFrame.disabled = true;
  photoFrame.setAttribute("aria-label", character.name + " 사진 크게 보기");
  statusLine.textContent = pickupStatus.textContent = "사진을 불러오는 중…";
  dialog.showModal();
  document.querySelector("#card-close").focus();
  dialog.scrollTop = 0;

  const image = new Image();
  image.alt = character.name;
  const photoUrl = character.photo + "?v=3";
  image.src = photoUrl;
  try {
    await image.decode();
    if (id !== viewId || !dialog.open) return;
    photoFrame.append(image);
    photoFrame.disabled = false;
    saveLink.href = photoUrl;
    saveLink.download = character.downloadName ?? character.photo.split("/").pop();
    saveLink.removeAttribute("aria-disabled");
    statusLine.textContent = pickupStatus.textContent = "";
  } catch {
    if (id === viewId && dialog.open) {
      statusLine.textContent = pickupStatus.textContent = "봇 PNG 준비 중";
    }
  }
}

